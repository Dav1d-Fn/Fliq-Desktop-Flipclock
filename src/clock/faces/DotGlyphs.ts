// Text as the dot matrix can show it: upper case (ß becomes SS), umlauts kept, other accents
// dropped, typographic dashes and ellipses as plain ones.
export function dotText(text: string): string
{
    return text
        .toUpperCase()
        .replace(/[^ÄÖÜ]/g, (character) => character.normalize("NFD").replace(/\p{M}/gu, ""))
        .replace(/[–—]/g, "-")
        .replace(/…/g, "...");
}
